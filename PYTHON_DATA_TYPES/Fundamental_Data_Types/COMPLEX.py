# Properties
# 'complex' is one of the pre-defined class and treated as Fundamental data type.
# The purpose of complex data type is that 'To Store complex value / Imaginary values'

# examples
a = 2+3j 
print(a,type(a)) #------------- (2+3j) <class 'complex'>

a = -2-4j
print(a, type(a)) #------------- (-2-4j) <class 'complex'>

b = 1.2+3.4j
print(b, type(b)) #------------- (1.2+3.4j) <class 'complex'>

b = 12+4.5J
print(b, type(b)) #------------- (12+4.5j) <class 'complex'>

c = 5j
print(c, type(c)) #------------- 5j <class 'complex'>

c = -5j
print(c, type(c)) #------------- (-0-5j) <class 'complex'>

d = -2.6j
print(d, type(d)) #------------- (-0-2.6j) <class 'complex'>

